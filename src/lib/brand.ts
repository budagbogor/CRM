export function buildComplaintRecoveryMessage(input: {
  customerName: string;
  ticketNumber: string;
  branchName: string;
}) {
  const customerName = formatCustomerName(input.customerName);
  return {
    subject: `Tindak lanjut komplain ${input.ticketNumber}`,
    message: `Halo ${customerName}, tim ${input.branchName} sedang menindaklanjuti komplain Anda dengan nomor ${input.ticketNumber}. Kami akan menghubungi Anda kembali secepatnya melalui WhatsApp ${brandIdentity.whatsappNumber}.`,
  };
}

export function buildNextServiceReminderMessage(input: {
  customerName: string;
  vehicleLabel: string;
  branchName: string;
  dueLabel?: string;
}) {
  const customerName = formatCustomerName(input.customerName);
  const dueCopy = input.dueLabel ? ` Jadwal ideal servis berikutnya ${input.dueLabel}.` : "";
  return {
    subject: `Pengingat servis ${input.vehicleLabel}`,
    message: `Halo ${customerName}, ${input.vehicleLabel} sudah masuk radar servis ${input.branchName}.${dueCopy} Balas pesan ini untuk booking cepat layanan Mobeng: ${brandIdentity.positioning}.`,
  };
}

export function buildBookingConfirmationMessage(input: {
  customerName: string;
  bookingNumber: string;
  branchName: string;
  scheduledStart: Date;
  requestedServices: string[];
}) {
  const customerName = formatCustomerName(input.customerName);
  const requestedServices =
    input.requestedServices.length > 0
      ? input.requestedServices.join(", ")
      : "servis kendaraan";
  return {
    subject: `Konfirmasi booking ${input.bookingNumber}`,
    message: `Halo ${customerName}, booking ${input.bookingNumber} di ${input.branchName} sudah kami terima untuk ${formatMobengDateTime(input.scheduledStart)}. Kebutuhan Anda: ${requestedServices}. Untuk perubahan jadwal, hubungi ${brandIdentity.whatsappNumber}.`,
  };
}

